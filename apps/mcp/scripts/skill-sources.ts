/**
 * The skills the MCP worker serves over the MCP Skills extension
 * (`io.modelcontextprotocol/skills`, SEP-2640). Each is read from its home in
 * the repo and embedded into `src/skill-bundles.ts`, because a Worker can't
 * read the repo at runtime.
 *
 * Only skills that make sense to a connected MCP client go here: the CLI skill
 * (`releases-cli`) and the operator skills under `.claude/skills/` stay out.
 */
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, resolve } from "node:path";

export const REPO_ROOT = resolve(import.meta.dir, "..", "..", "..");

export const MCP_SKILLS: { name: string; dir: string }[] = [
  { name: "releases-mcp", dir: "plugins/claude/releases/skills" },
  { name: "analyzing-releases", dir: "plugins/claude/releases/skills" },
  { name: "creating-releases-json", dir: "skills" },
];

/** Every file of every served skill, keyed `<skill>/<relative path>`, sorted. */
export function collectSkillFiles(root: string = REPO_ROOT): Record<string, string> {
  const out: Record<string, string> = {};
  for (const { name, dir } of MCP_SKILLS) {
    const base = join(root, dir, name);
    const walk = (rel: string) => {
      const abs = join(base, rel);
      for (const entry of readdirSync(abs).sort()) {
        const childRel = rel ? `${rel}/${entry}` : entry;
        if (statSync(join(base, childRel)).isDirectory()) walk(childRel);
        else out[`${name}/${childRel}`] = readFileSync(join(base, childRel), "utf8");
      }
    };
    walk("");
    if (!out[`${name}/SKILL.md`]) throw new Error(`Skill ${name} has no SKILL.md in ${dir}`);
  }
  return out;
}

export function renderSkillBundle(files: Record<string, string>): string {
  return [
    "// AUTO-GENERATED by apps/mcp/scripts/build-skills.ts — do not edit by hand.",
    "// Regenerate with `bun run mcp:skills:build` from the repo root.",
    "",
    "export const SKILL_FILES: Record<string, string> = " + JSON.stringify(files, null, 2) + ";",
    "",
  ].join("\n");
}
